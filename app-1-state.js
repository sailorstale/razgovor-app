// Заголовок раздела плюс группа строк под ним.
function uiSection(label, rows){
  const body = (rows||[]).filter(Boolean).join('');
  if(!body) return '';
  return (label?`<div class="settings-group-label">${esc(label)}</div>`:'') + `<div class="cg-section">${body}</div>`;
}

// Строка списка — один сборщик на всю взрослую зону. Слева необязательный значок
// (`icon`) или своя картинка (`leadHtml`); в конце одно из
// трёх: стрелка у перехода на экран (`go`), отметка выбора (`radio`), ничего у действия
// (`action`); `trailHtml` добавляет кнопку справа, `foot` — ряд кнопок под текстом,
// `href` делает строку ссылкой. Так профиль, голос, результат поиска и пункт настроек
// собираются из одной разметки и выглядят одинаково.
function uiRow(o){
  const lead  = o.icon ? `<div class="cgi-icon" data-mi="${o.icon}"></div>`
              : o.leadHtml ? `<div class="cgi-icon cgi-lead">${o.leadHtml}</div>` : '';
  const desc  = o.desc ? `<div class="cgi-desc">${o.descHtml?o.desc:esc(o.desc)}</div>` : '';
  const value = o.value ? `<span class="cgi-value">${esc(o.value)}</span>` : '';
  const trail = (o.go ? `<span class="cgi-arrow">${mi('chevr')}</span>` : '')
              + (o.radio!==undefined ? `<div class="ui-radio${o.radio?' on':''}"></div>` : '')
              + (o.trailHtml||'');
  const title = `<div class="cgi-title${o.danger?' is-danger':''}">${o.titleHtml?o.title:esc(o.title)}</div>`;
  const main  = `${lead}<div class="cgi-text">${title}${desc}</div>${value}${trail}`;
  const id    = o.id ? ` id="${o.id}"` : '';
  const cls   = 'cg-item' + (o.cls?' '+o.cls:'');
  if(o.href) return `<a class="${cls}" href="${o.href}"${id}>${main}</a>`;
  const click = (typeof o.go==='string' ? o.go : '') || o.action || '';
  // Атрибут onclick ставим только строке с действием: по нему стили решают, подсвечивать ли нажатие.
  const on    = click ? ` onclick="${click}"` : '';
  if(o.foot) return `<div class="${cls} cg-item-stack"${id}><div class="cgi-main"${on}>${main}</div><div class="cgi-foot">${o.foot}</div></div>`;
  return `<div class="${cls}"${on}${id}>${main}</div>`;
}

// Строка с переключателем. Состояние берётся из настройки, обработчик один на все.
function uiToggle(o){
  const icon = o.icon ? `<div class="cgi-icon" data-mi="${o.icon}"></div>` : '';
  const desc = o.desc ? `<div class="cgi-desc">${o.descHtml?o.desc:esc(o.desc)}</div>` : '';
  return `<div class="cg-item toggle-row">
    <div class="cgi-main">${icon}<div class="cgi-text"><div class="cgi-title">${esc(o.title)}</div>${desc}</div></div>
    <div class="toggle-switch${o.on?' on':''}" id="${o.id}"${o.setting?` data-setting="${o.setting}"`:''} role="switch" aria-checked="${o.on?'true':'false'}" onclick="toggleSwitch(this)"></div></div>`;
}

// Строка с выбором из двух-трёх значений.
function uiSegment(o){
  const icon = o.icon ? `<div class="cgi-icon" data-mi="${o.icon}"></div>` : '';
  const desc = o.desc ? `<div class="cgi-desc">${o.descHtml?o.desc:esc(o.desc)}</div>` : '';
  const opts = o.options.map(x=>`<div class="gs-opt${x.html?' gs-opt-card':''}${x.active?' active':''}" onclick="${x.action}">${x.html||esc(x.label)}</div>`).join('');
  return `<div class="cg-item cg-item-stack">
    <div class="cgi-main">${icon}<div class="cgi-text"><div class="cgi-title">${esc(o.title)}</div>${desc}</div></div>
    <div class="gs-options">${opts}</div></div>`;
}

// Пустое состояние: что здесь будет, почему пусто и что нажать (R-H9).
function uiEmpty(text, btnLabel, btnAction){
  const btn = btnLabel ? `<button class="btn-full ui-empty-btn" onclick="${btnAction}">${esc(btnLabel)}</button>` : '';
  return `<div class="ui-empty">${esc(text)}${btn}</div>`;
}

