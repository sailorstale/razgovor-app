const ARASAAC_IDS = {};
// URL картинки по id с учётом выбора «цветные/чёрно-белые» и нужного размера.
// size — сторона картинки в пикселях: крупные карточки доски берут 500 (по
// умолчанию), мелкие поверхности (core-bar, лента, вкладки категорий, ~24-40px) —
// 300, это экономит больше половины байт и памяти на слабом планшете. Цветной путь
// (static) отдаёт 300 напрямую; чёрно-белый (API) принимает только 500 и 2500,
// поэтому там меньше 500 не просим (при промахе всё равно сработает заглушка onerror).
function arasaacUrl(id, size){
  size = size || 500;
  return S.arasaacColor
    ? `https://static.arasaac.org/pictograms/${id}/${id}_${size}.png`
    : `https://api.arasaac.org/v1/pictograms/${id}?color=false&resolution=${size<500?500:size}&download=false`;
}
let _araSaveT=null;
function persistSoon(){ clearTimeout(_araSaveT); _araSaveT=setTimeout(persist, 800); }  // копим правки кэша, сохраняем разом
// Неудачные запросы (нет сети, сервер отвечает ошибкой) не кэшируются намеренно:
// картинка может появиться позже. Но повторять их на КАЖДУЮ перерисовку нельзя —
// при плохой связи это десятки запросов подряд. Держим короткую паузу перед новой
// попыткой по тому же слову.
const ARASAAC_RETRY_MS=60000;
const arasaacFailedAt={};
async function fetchArasaacId(lemma) {
  // Картинка лежит внутри приложения и будет показана — запрос наружу не нужен.
  // В чёрно-белом режиме встроенная цветная копия не годится, и слово ищем в сети как любое.
  if (localPictoUrl(lemma)) return null;
  if (lemma in ARASAAC_IDS) return ARASAAC_IDS[lemma];
  const failed=arasaacFailedAt[lemma];
  if (failed && Date.now()-failed < ARASAAC_RETRY_MS) return null;
  try {
    const res = await fetch(
      `https://api.arasaac.org/v1/pictograms/ru/search/${encodeURIComponent(lemma)}`,
      { method:'GET', mode:'cors', headers:{ 'Accept':'application/json' } }
    );
    // Отмечаем неудачу, иначе откат по времени (ARASAAC_RETRY_MS) не работает
    // и слово запрашивается снова при каждой перерисовке.
    if (!res.ok) { arasaacFailedAt[lemma] = Date.now(); return null; }
    const data = await res.json();
    if (!data || !data.length) { ARASAAC_IDS[lemma] = null; persistSoon(); return null; }  // точно нет — кэшируем
    ARASAAC_IDS[lemma] = data[0]._id; persistSoon();
    return ARASAAC_IDS[lemma];
  } catch(e) {
    console.warn('[ARASAAC] fetch failed for «' + lemma + '»:', e.message);
    arasaacFailedAt[lemma] = Date.now();
    return null;                                       // нет сети — покажем заглушку, повторим позже
  }
}

// После рендера — асинхронно подгружаем ARASAAC-картинки в карточки
function loadArasaacImages() {
  if (S.imageLibrary !== 'arasaac') return;
  document.querySelectorAll('.picto-card[data-lemma]').forEach(async card => {
    if (card.dataset.hasPhoto === '1') return;
    const lemma = card.dataset.lemma;
    if (!lemma) return;
    const id = await fetchArasaacId(lemma);
    // После await — ищем карточку заново в живом DOM
    const live = document.querySelector(`.picto-card[data-lemma="${CSS.escape(lemma)}"]`);
    if (!live || live.dataset.hasPhoto === '1') return;
    const wrap = live.querySelector('.picto-img-wrap');
    if (!wrap) return;
    if (!id) {  // не найдено или нет сети — нейтральная заглушка вместо вечного спиннера
      if (wrap.querySelector('.picto-spinner')) wrap.innerHTML = symbolStub();
      return;
    }
    // Нужная картинка уже стоит (renderPictograms вставил её для известного id, или
    // это повторная перерисовка) — не пересоздаём: иначе лишний ре-декод и мигание.
    // Сравниваем с учётом выбора цвет/ч-б: если он сменился, src другой — обновим.
    const cur = wrap.querySelector('img.picto-arasaac');
    if (cur && cur.getAttribute('src') === arasaacUrl(id)) return;
    // Создаём img через DOM API — без проблем с HTML-экранированием
    const img = document.createElement('img');
    img.className = 'picto-arasaac';
    img.alt = '';   // декоративно: рядом всегда текст-подпись (R-I9)
    img.onerror = function() { arasaacFallback(this); };
    wrap.innerHTML = '';
    wrap.appendChild(img);
    img.src = arasaacUrl(id); // src последним — чтобы onerror был навешан до начала загрузки
  });
}

