// Прототип построен на <div onclick>. Вместо переписывания всех в <button> (риск
// для вёрстки) — единый идемпотентный пост-рендер-проход: проставляем role/tabindex/
// aria, а Enter/Space обрабатываем делегированием (см. keydown ниже). Так интерфейс
