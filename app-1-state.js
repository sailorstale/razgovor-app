// Файлы лежат цветными. В чёрно-белом режиме поведение прежнее — картинка берётся
// с сервера, потому что своей чёрно-белой копии у нас нет.
// У карточки картинку ищем по полю pic (если задано), иначе по лемме: так зачин
// «я хочу» берёт картинку слова «хотеть», а папка «Еда» — картинку «еда».
function picKey(w){ return (w && (w.pic || w.lemma)) || ''; }
function localPictoUrl(lemma){
  if(!lemma || !LOCAL_PICTOS.has(lemma)) return null;
  if(typeof S!=='undefined' && S.imageLibrary==='arasaac' && S.arasaacColor===false) return null;
  return 'pictos/' + lemma.replace(/[^а-яёa-z0-9]/gi,'_') + '.png';
}

function arasaacFallback(img) {
  if (img.parentNode) img.parentNode.innerHTML = symbolStub();
}
