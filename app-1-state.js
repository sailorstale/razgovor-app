// Проверка обработчиков (только на отладке). Инлайновый onclick вызывает функцию
// по голому имени, а функция должна быть глобальной. Опечатка или переименование в
// одном месте из шести файлов не роняет код — кнопка молча не работает, пока
// пользователь до неё не дойдёт. Здесь вытаскиваем имена вызываемых функций из
// строки onclick и, если такой глобальной функции нет, предупреждаем в консоль ОДИН
// раз на имя. В бою (не localhost) проверка не запускается — цена ноль.
const DEV_HOST = typeof location!=='undefined' &&
  (/^(localhost|127\.0\.0\.1|\[::1\])$/i.test(location.hostname) || location.hostname.endsWith('.local'));
const _warnedHandlers = new Set();
// ключевые слова языка, за которыми тоже идёт «(» — это не вызовы функций
const _handlerSkip = new Set(['if','for','while','switch','return','typeof','catch','function','do','else','void','delete','new','await']);
function checkOnclickHandlers(el, oc){
  // имя перед «(», НЕ после точки (чтобы event.stopPropagation() и Math.max() не считались)
  const names = oc.match(/(?:^|[^.\w$])([a-zA-Z_$][\w$]*)\s*\(/g) || [];
  for(const raw of names){
    const name = raw.replace(/[^\w$]*$/,'').replace(/^[^a-zA-Z_$]*/,'').replace(/\s*$/,'').replace(/\($/,'').trim();
    if(!name || _handlerSkip.has(name) || _warnedHandlers.has(name)) continue;
    if(typeof window[name] !== 'function'){
      _warnedHandlers.add(name);
      console.warn(`[handlers] onclick зовёт «${name}(…)», но такой глобальной функции нет — опечатка или переименование? Элемент:`, el);
    }
  }
}
// Клавиатурного доступа в продукте нет: роли, порядок обхода, обработка Enter и
// пробела и обводка фокуса убраны решением от 25 августа. Сейчас важно собрать общую
// механику, к доступности возвращаемся на зрелом продукте. Функция оставлена пустой,
// чтобы не разбирать полсотни мест вызова: вернуть слой будет одним движением.
// Что здесь остаётся — сверка имён обработчиков на отладке: она про опечатки в коде,
// а не про доступность, и ловит переименования до того, как их увидит человек.
function a11yEnhance(root){
  if(!DEV_HOST) return;
  (root || document).querySelectorAll('[onclick]').forEach(el=>{
    checkOnclickHandlers(el, el.getAttribute('onclick')||'');
  });
}

