// ===== ЕДИНЫЙ ВИЗУАЛЬНЫЙ ЯЗЫК СИМВОЛОВ (R-C4b) =====
// Одна система символов на всех детских поверхностях. Раньше сетка показывала
// ARASAAC, а строка ключевых слов, собранная фраза и поиск — эмодзи: один и
// тот же предмет выглядел по-разному в двух местах одного экрана. Эмодзи на
// детских поверхностях не используются вообще.
// Порядок выбора: своё фото → ARASAAC → (ещё грузится) → нейтральная заглушка.
function symbolStub(){
  // Не эмодзи и не буква: у слова всегда есть подпись, а чужой стиль ломает
  // единообразие. Взрослого при этом отдельно подталкиваем добавить фото.
  return '<span class="sym-stub" aria-hidden="true"></span>';
}
// Строка ключевых слов и собранная фраза рисуются одним проходом и своего
// DOM-патчинга не имеют (в отличие от сетки). Поэтому: дозапрашиваем id
// пиктограмм для их слов и один раз перерисовываем — иначе там навсегда
// оставался бы спиннер. Повторного круга не будет: после ответа id уже
// определён (число или null), и need становится пустым.
// Одна попытка на слово за сессию. Без этого получается вечный цикл: слово,
// которого нет в ARASAAC (404), навсегда остаётся «неизвестным», перерисовка
// снова просит его загрузить, та снова перерисовывает — и так до бесконечности,
// долбя чужой API. Проверено: именно так и случилось на «Помогите» и «Смотри».
const arasaacTried = new Set();
async function ensureSymbolsFor(words, rerender){
  if(S.imageLibrary!=='arasaac') return;
  // Слово со встроенной картинкой не ищем и не помечаем как «пробовали»: в чёрно-белом
  // режиме встроенной копии нет (localPictoUrl даёт null), и тогда его нужно искать в сети.
  const need=[...new Set((words||[]).map(w=>picKey(w))
    .filter(l=>l && !localPictoUrl(l) && ARASAAC_IDS[l]===undefined && !arasaacTried.has(l)))];
  if(!need.length) return;
  need.forEach(l=>arasaacTried.add(l));
  await Promise.all(need.map(l=>fetchArasaacId(l).catch(()=>null)));
  if(typeof rerender==='function') rerender();
}
// ===== КАКАЯ У СЛОВА КАРТИНКА =====
// Одно решение на все места, где рисуется символ: клетка окна, строка фразы, строки
// поиска, мелкий значок, картинка для «Поделиться». Лестница выбора — своё фото, символ
// выбранный помощником, копия внутри приложения, символ из сети, заглушка — до
// 23 сентября 2026 года была написана трижды в трёх файлах, с разными классами и
// размерами, и «Поделиться» вместо неё читало адреса обратно из нарисованного экрана.
//
// Отдаёт {kind, src}: photo — фото помощника, picto — пиктограмма, loading — ещё ищем,
// stub — искали и не нашли. size это сторона картинки: крупная клетка берёт 500 по
// умолчанию, мелкие поверхности — 300.
function wordImage(w, size){
  if(!w) return {kind:'stub'};
  if(w.photo) return {kind:'photo', src:w.photo};
  if(w.pictoId) return {kind:'picto', src:arasaacUrl(w.pictoId, size)};
  const key=picKey(w);
  const local=localPictoUrl(key);               // картинка лежит внутри — в сеть не идём
  if(local) return {kind:'picto', src:local};
  const id=ARASAAC_IDS[key];
  if(id) return {kind:'picto', src:arasaacUrl(id, size)};
  // Спиннер показываем, только пока попытка ещё не сделана. Слово уже искали и не
  // нашли (404) — вечное «грузится» хуже заглушки: ребёнок ждёт картинку, которой не будет.
  if(id===undefined && S.imageLibrary==='arasaac' && !arasaacTried.has(key)) return {kind:'loading'};
  return {kind:'stub'};
}

// Разметка мелкого символа: строка фразы, строки поиска, боковой столбец.
function symbolInner(w){
  const im=wordImage(w, 300);
  if(im.kind==='photo') return `<img class="sym-img" src="${im.src}" alt="">`;
  if(im.kind==='picto') return `<img class="sym-img" src="${im.src}" alt="" onerror="arasaacFallback(this)">`;
  if(im.kind==='loading') return '<span class="sym-loading" aria-hidden="true"></span>';
  return symbolStub();
}

